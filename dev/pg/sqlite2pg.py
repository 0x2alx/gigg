#!/usr/bin/env python3
"""Translate gigg's SQLite schema (sqlite3 .schema output) into the PostgreSQL baseline schema.

Usage: sqlite2pg.py schema.sql > internal/store/migrations_pg/NNNN_baseline.sql

The output is reviewed and committed; this script is the record of how it was made. Rules:
- INTEGER -> BIGINT, REAL -> DOUBLE PRECISION, BLOB -> BYTEA, STRICT dropped;
- a single-column INTEGER PRIMARY KEY (AUTOINCREMENT or not) -> BIGINT identity;
- COLLATE NOCASE columns -> citext (case-insensitive compare and uniqueness, as in SQLite);
- GLOB checks -> anchored regular expressions; json_valid/json_type -> jsonb casts;
- every REFERENCES becomes an ALTER TABLE ... ADD FOREIGN KEY after all tables exist (SQLite lets a
  table point at one defined later, PostgreSQL doesn't);
- BEFORE DELETE/UPDATE ... RAISE(ABORT) triggers -> a plpgsql function that raises.
"""
import re
import sys

src = open(sys.argv[1]).read()


def split_top(s, sep=","):
    out, depth, cur, q = [], 0, "", None
    for ch in s:
        if q:
            cur += ch
            if ch == q:
                q = None
            continue
        if ch in "'\"":
            q = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return out


def glob_to_re(g):
    out = ""
    i = 0
    while i < len(g):
        c = g[i]
        if c == "*":
            out += ".*"
        elif c == "?":
            out += "."
        elif c == "[":
            j = g.index("]", i)
            out += g[i : j + 1]
            i = j
        elif c in ".^$+(){}|\\":
            out += "\\" + c
        else:
            out += c
        i += 1
    if out.endswith(".*"):
        return "^" + out[:-2]
    return "^" + out + "$"


def expr(e):
    e = re.sub(r"(\w+)\s+GLOB\s+'([^']*)'", lambda m: f"{m.group(1)} ~ '{glob_to_re(m.group(2))}'", e)
    e = re.sub(r"\bIFNULL\(", "COALESCE(", e, flags=re.I)
    e = re.sub(r"json_valid\((\w+)\)", r"(\1::jsonb IS NOT NULL)", e)
    e = re.sub(r"json_type\((\w+)\)", r"jsonb_typeof(\1::jsonb)", e)
    e = re.sub(r"length\(CAST\((\w+) AS BLOB\)\)", r"octet_length(\1)", e)
    return e


TYPES = {"INTEGER": "BIGINT", "REAL": "DOUBLE PRECISION", "BLOB": "BYTEA", "TEXT": "TEXT"}
fks = []  # (table, column(s), ref table, ref col, on delete)
tables_out, indexes_out, triggers_out = [], [], []

# statements: sqlite3 .schema ends each with ";" at line end (triggers are one line each here)
stmts = [s.strip() for s in re.split(r";\s*\n", src) if s.strip()]
for st in stmts:
    st = st.rstrip(";")
    if st.startswith("CREATE TABLE sqlite_sequence") or "schema_migrations" in st.split("(")[0]:
        continue
    m = re.match(r'CREATE TABLE (?:IF NOT EXISTS )?"?(\w+)"?\s*\((.*)\)\s*(STRICT)?\s*$', st, re.S)
    if m:
        name, body = m.group(1), m.group(2)
        body = re.sub(r"--[^\n]*", "", body)  # comments first: they may hold commas
        items = []
        for raw in split_top(body):
            it = raw.strip()
            if not it:
                continue
            up = it.split()[0].upper()
            if up in ("PRIMARY", "UNIQUE", "CHECK", "CONSTRAINT"):
                items.append("  " + expr(it))
                continue
            if up == "FOREIGN":
                fm = re.match(r"FOREIGN KEY\s*\(([^)]*)\)\s*REFERENCES\s+\"?(\w+)\"?\s*\(([^)]*)\)(.*)$", it, re.S)
                assert fm, it
                fks.append((name, fm.group(1), fm.group(2), fm.group(3), fm.group(4).strip()))
                continue
            col = it.split()[0].strip('"')
            rest = it[len(it.split()[0]):].strip()
            typ = rest.split()[0] if rest else ""
            rest = rest[len(typ):].strip()
            # REFERENCES -> later
            rm = re.search(r"REFERENCES\s+\"?(\w+)\"?\s*\((\w+)\)((?:\s+ON (?:DELETE|UPDATE) (?:CASCADE|SET NULL|RESTRICT|NO ACTION|SET DEFAULT))*)", rest)
            if rm:
                fks.append((name, col, rm.group(1), rm.group(2), rm.group(3).strip()))
                rest = (rest[: rm.start()] + rest[rm.end():]).strip()
            nocase = "COLLATE NOCASE" in rest
            rest = rest.replace("COLLATE NOCASE", "").strip()
            if re.match(r"PRIMARY KEY(\s+AUTOINCREMENT)?", rest) and typ == "INTEGER":
                rest = re.sub(r"PRIMARY KEY(\s+AUTOINCREMENT)?", "", rest).strip()
                pgt = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            else:
                pgt = "citext" if nocase else TYPES.get(typ, typ)
            line = f"  {col} {pgt} {expr(rest)}".rstrip()
            items.append(re.sub(r"\s+", " ", line).replace("  ", " ") if "\n" not in line else line)
        tables_out.append(f"CREATE TABLE {name} (\n" + ",\n".join("  " + i.strip() for i in items) + "\n);")
        continue
    m = re.match(r"CREATE (UNIQUE )?INDEX (\w+) ON \"?(\w+)\"?\s*(.*)$", st, re.S)
    if m:
        body = m.group(4).replace("COLLATE NOCASE", "")
        indexes_out.append(f"CREATE {m.group(1) or ''}INDEX {m.group(2)} ON {m.group(3)} {expr(body).strip()};")
        continue
    m = re.match(r"CREATE TRIGGER (\w+) BEFORE (DELETE|UPDATE) ON (\w+) BEGIN SELECT RAISE\(ABORT, '([^']*)'\); END$", st)
    if m:
        trig, ev, tbl, msg = m.groups()
        triggers_out.append(
            f"CREATE FUNCTION {trig}_fn() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION '{msg}'; END $$;\n"
            f"CREATE TRIGGER {trig} BEFORE {ev} ON {tbl} FOR EACH ROW EXECUTE FUNCTION {trig}_fn();"
        )
        continue
    sys.exit("unhandled statement:\n" + st[:300])

print("-- gigg PostgreSQL baseline: the schema SQLite reaches after every migration up to this number.")
print("-- Made by dev/pg/sqlite2pg.py from the SQLite schema, then reviewed. Later migrations add a")
print("-- migrations_pg/NNNN_*.sql twin for each migrations/NNNN_*.sql.")
print("CREATE EXTENSION IF NOT EXISTS citext;\n")
for t in tables_out:
    print(t + "\n")
for i in indexes_out:
    print(i)
print()
for (t, c, rt, rc, od) in fks:
    print(f"ALTER TABLE {t} ADD FOREIGN KEY ({c.strip()}) REFERENCES {rt} ({rc.strip()}){(' ' + od) if od else ''};")
print()
for t in triggers_out:
    print(t)
