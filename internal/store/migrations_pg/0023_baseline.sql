  followers TEXT NOT NULL DEFAULT '[]' CHECK ((followers::jsonb IS NOT NULL)),
  start_category TEXT NOT NULL DEFAULT '' CHECK (start_category IN ('', 'backlog', 'todo')),
  CHECK (workspace_id IS NOT NULL OR (project_id IS NULL AND custom = '{}'))
);

CREATE TABLE errand_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  description_md TEXT NOT NULL DEFAULT '' CHECK (length(description_md) <= 65536),
  command TEXT NOT NULL CHECK (length(command) BETWEEN 1 AND 16384),
  timeout_s BIGINT NOT NULL DEFAULT 300 CHECK (timeout_s BETWEEN 10 AND 43200),
  output TEXT NOT NULL DEFAULT 'gigg' CHECK (output IN ('gigg', 'host')),
  unsandboxed BIGINT NOT NULL DEFAULT 0 CHECK (unsandboxed IN (0, 1)),
  command_set_by BIGINT NOT NULL,
  command_set_at BIGINT NOT NULL,
  unsandboxed_set_by BIGINT,
  created_by BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  deleted_at BIGINT,
  version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE schedules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  freq TEXT NOT NULL CHECK (freq IN ('minutes', 'hours', 'daily', 'weekly', 'monthly')),
  interval_n BIGINT NOT NULL DEFAULT 1 CHECK (interval_n BETWEEN 1 AND 365),
  weekdays TEXT NOT NULL DEFAULT '[]' CHECK ((weekdays::jsonb IS NOT NULL)),
  month_day BIGINT CHECK (month_day IS NULL OR month_day BETWEEN -1 AND 31 AND month_day != 0),
  tz TEXT NOT NULL DEFAULT 'UTC',
  window_start TEXT NOT NULL DEFAULT '00:00' CHECK (window_start ~ '^[0-2][0-9]:[0-5][0-9]$'),
  window_minutes BIGINT NOT NULL DEFAULT 1440 CHECK (window_minutes BETWEEN 5 AND 44640),
  lead_minutes BIGINT NOT NULL DEFAULT 0 CHECK (lead_minutes BETWEEN 0 AND 10080),
  created_by BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  deleted_at BIGINT,
  version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE access_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  group_id BIGINT,
  workspace_id BIGINT,
  preset TEXT NOT NULL DEFAULT '' CHECK (preset IN ('', 'viewer', 'consumer', 'member', 'manager')),
  overrides TEXT NOT NULL DEFAULT '{}' CHECK ((overrides::jsonb IS NOT NULL) AND jsonb_typeof(overrides::jsonb) = 'object'),
  created_at BIGINT NOT NULL,
  project_id BIGINT,
  CHECK ((user_id IS NULL) != (group_id IS NULL))
);

CREATE TABLE api_key_reach (
  key_id BIGINT NOT NULL,
  position BIGINT NOT NULL,
  workspace_id BIGINT NOT NULL,
  project_id BIGINT
);

CREATE TABLE api_keys (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 64),
  prefix TEXT NOT NULL UNIQUE,
  secret_hash BYTEA NOT NULL,
  user_id BIGINT NOT NULL,
