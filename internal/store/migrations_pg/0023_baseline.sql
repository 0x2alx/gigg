-- gigg PostgreSQL baseline: the schema SQLite reaches after every migration up to this number.
-- Made by dev/pg/sqlite2pg.py from the SQLite schema, then reviewed. Later migrations add a
-- migrations_pg/NNNN_*.sql twin for each migrations/NNNN_*.sql.
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE instance (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id = 1),
  created_at BIGINT NOT NULL
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username citext NOT NULL UNIQUE CHECK (username ~ '^[a-z]' AND length(username) BETWEEN 2 AND 32),
  kind TEXT NOT NULL CHECK (kind IN ('human', 'agent')),
  display_name TEXT NOT NULL DEFAULT '' CHECK (length(display_name) <= 64),
  description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 200),
  color TEXT CHECK (color IS NULL OR color ~ '^#[0-9A-F][0-9A-F][0-9A-F][0-9A-F][0-9A-F][0-9A-F]$'),
  avatar_sha256 TEXT,
  password_hash TEXT,
  is_admin BIGINT NOT NULL DEFAULT 0 CHECK (is_admin IN (0, 1)),
  disabled_at BIGINT,
  preferences TEXT NOT NULL DEFAULT '{}' CHECK ((preferences::jsonb IS NOT NULL)),
  theme_selected_id TEXT,
  theme_match_system BIGINT NOT NULL DEFAULT 0 CHECK (theme_match_system IN (0, 1)),
  last_login_at BIGINT,
  created_at BIGINT NOT NULL,
  version BIGINT NOT NULL DEFAULT 1,
  CHECK (kind = 'human' OR password_hash IS NULL)
);

CREATE TABLE user_themes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  theme_id TEXT NOT NULL,
  theme TEXT NOT NULL CHECK ((theme::jsonb IS NOT NULL)),
  updated_at BIGINT NOT NULL,
  UNIQUE (user_id, theme_id)
);

CREATE TABLE sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  token_hash BYTEA NOT NULL UNIQUE,
  created_at BIGINT NOT NULL,
  last_seen_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  ip TEXT NOT NULL DEFAULT '',
  user_agent TEXT NOT NULL DEFAULT '',
  revoked_at BIGINT
);

CREATE TABLE workspaces (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z]' AND length(slug) BETWEEN 2 AND 32),
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 64),
  color TEXT,
  description_md TEXT NOT NULL DEFAULT '' CHECK (length(description_md) <= 65536),
  status_template TEXT NOT NULL CHECK ((status_template::jsonb IS NOT NULL)),
  archived_at BIGINT,
  created_at BIGINT NOT NULL,
  version BIGINT NOT NULL DEFAULT 1,
  owner_id BIGINT,
  attach_file_max BIGINT CHECK (attach_file_max IS NULL OR attach_file_max > 0),
  attach_quota BIGINT CHECK (attach_quota IS NULL OR attach_quota > 0)
);

CREATE TABLE statuses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  project_id BIGINT NOT NULL,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 40),
  category TEXT NOT NULL CHECK (category IN ('backlog', 'todo', 'doing', 'waiting', 'done', 'cancelled')),
  color TEXT,
  position DOUBLE PRECISION NOT NULL,
  wip_limit BIGINT,
  is_default BIGINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
  version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE gigs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  project_id BIGINT NOT NULL,
  number BIGINT NOT NULL,
  title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 250),
  description_md TEXT NOT NULL DEFAULT '' CHECK (length(description_md) <= 65536),
  status_id BIGINT NOT NULL,
  position DOUBLE PRECISION NOT NULL,
  priority BIGINT NOT NULL DEFAULT 0 CHECK (priority BETWEEN 0 AND 4),
  color TEXT,
  start_at BIGINT,
  due_at BIGINT,
  done_at BIGINT,
  parent_id BIGINT,
  cloned_from_id BIGINT,
  created_by BIGINT NOT NULL,
  created_via_key_id BIGINT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  session_id TEXT,
  last_run_id BIGINT,
  resume_requested_at BIGINT,
  cost_usd_total DOUBLE PRECISION NOT NULL DEFAULT 0,
  comment_count BIGINT NOT NULL DEFAULT 0,
  deleted_at BIGINT,
  deleted_by BIGINT,
  version BIGINT NOT NULL DEFAULT 1,
  recurrence_id BIGINT,
  occurrence_at BIGINT,
  not_after BIGINT,
  missed_at BIGINT,
  archived_at BIGINT,
  model TEXT NOT NULL DEFAULT '' CHECK (length(model) <= 64),
  effort TEXT NOT NULL DEFAULT '' CHECK (effort IN ('', 'low', 'medium', 'high', 'xhigh', 'max')),
  always_run BIGINT NOT NULL DEFAULT 0 CHECK (always_run IN (0, 1)),
  allowed_tools TEXT NOT NULL DEFAULT '[]' CHECK ((allowed_tools::jsonb IS NOT NULL)),
  blocks_parent BIGINT NOT NULL DEFAULT 0 CHECK (blocks_parent IN (0, 1)),
  auto_archive_minutes BIGINT CHECK (auto_archive_minutes IS NULL OR auto_archive_minutes BETWEEN 5 AND 527040),
  run_timeout_minutes BIGINT CHECK (run_timeout_minutes IS NULL OR run_timeout_minutes BETWEEN 5 AND 300),
  last_progress_at BIGINT,
  UNIQUE (project_id, number)
);

CREATE TABLE gig_aliases (
  gig_id BIGINT NOT NULL,
  workspace_id BIGINT NOT NULL,
  project_key TEXT NOT NULL,
  number BIGINT NOT NULL,
  PRIMARY KEY (workspace_id, project_key, number)
);

CREATE TABLE gig_assignees (
  gig_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  PRIMARY KEY (gig_id, user_id)
);

CREATE TABLE labels (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  name citext NOT NULL CHECK (length(name) BETWEEN 1 AND 40),
  color TEXT,
  description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 200),
  version BIGINT NOT NULL DEFAULT 1,
  UNIQUE (workspace_id, name)
);

CREATE TABLE gig_labels (
  gig_id BIGINT NOT NULL,
  label_id BIGINT NOT NULL,
  PRIMARY KEY (gig_id, label_id)
);

CREATE TABLE run_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL,
  at BIGINT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('progress', 'note', 'artifact', 'state')),
  text TEXT NOT NULL DEFAULT '' CHECK (length(text) <= 2048),
  pct BIGINT
);

CREATE TABLE comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  gig_id BIGINT NOT NULL,
  author_id BIGINT NOT NULL,
  key_id BIGINT,
  kind TEXT NOT NULL CHECK (kind IN ('comment', 'report', 'question', 'resume_request', 'system')),
  body_md TEXT NOT NULL CHECK (length(body_md) BETWEEN 1 AND 65536),
  run_id BIGINT,
  created_at BIGINT NOT NULL,
  edited_at BIGINT,
  deleted_at BIGINT,
  version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE blobs (
  sha256 TEXT PRIMARY KEY,
  size BIGINT NOT NULL,
  refcount BIGINT NOT NULL DEFAULT 0,
  orphaned_at BIGINT
);

CREATE TABLE activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at BIGINT NOT NULL,
  workspace_id BIGINT,
  project_id BIGINT,
  actor_user_id BIGINT,
  key_id BIGINT,
  listener TEXT NOT NULL DEFAULT '',
  ip TEXT NOT NULL DEFAULT '',
  request_id TEXT NOT NULL DEFAULT '',
  action TEXT NOT NULL,
  entity_type TEXT NOT NULL DEFAULT '',
  entity_id BIGINT,
  data TEXT NOT NULL DEFAULT '{}' CHECK ((data::jsonb IS NOT NULL))
);

CREATE TABLE idempotency_keys (
  principal TEXT NOT NULL,
  key TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  status BIGINT NOT NULL,
  response BYTEA NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (principal, key)
);

CREATE TABLE gig_relations (
  workspace_id BIGINT NOT NULL,
  from_gig_id BIGINT NOT NULL,
  to_gig_id BIGINT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('blocks', 'relates')),
  created_by BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (from_gig_id, to_gig_id, kind),
  CHECK (from_gig_id != to_gig_id)
);

CREATE TABLE checklist_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  gig_id BIGINT NOT NULL,
  position DOUBLE PRECISION NOT NULL,
  text TEXT NOT NULL CHECK (length(text) BETWEEN 1 AND 500),
  done_at BIGINT,
  done_by BIGINT,
  created_at BIGINT NOT NULL
);

CREATE TABLE custom_fields (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 60),
  kind TEXT NOT NULL CHECK (kind IN ('text', 'number', 'date', 'select', 'checkbox', 'url')),
  options TEXT NOT NULL DEFAULT '[]' CHECK ((options::jsonb IS NOT NULL)),
  position DOUBLE PRECISION NOT NULL,
  created_at BIGINT NOT NULL,
  deleted_at BIGINT,
  version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE gig_custom_values (
  gig_id BIGINT NOT NULL,
  field_id BIGINT NOT NULL,
  value TEXT NOT NULL CHECK ((value::jsonb IS NOT NULL)),
  PRIMARY KEY (gig_id, field_id)
);

CREATE TABLE saved_filters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  workspace_id BIGINT,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 60),
  query TEXT NOT NULL CHECK ((query::jsonb IS NOT NULL)),
  position DOUBLE PRECISION NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 60),
  description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 500),
  created_at BIGINT NOT NULL,
  version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE group_members (
  group_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  PRIMARY KEY (group_id, user_id)
);

CREATE TABLE runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  gig_id BIGINT NOT NULL,
  worker_user_id BIGINT NOT NULL,
  key_id BIGINT,
  session_id TEXT,
  mode TEXT NOT NULL DEFAULT '' CHECK (length(mode) <= 32),
  attempt BIGINT NOT NULL DEFAULT 1,
  status TEXT NOT NULL CHECK (status IN ('running', 'done', 'needs_human', 'error', 'timeout', 'interrupted', 'parked')),
  started_at BIGINT NOT NULL,
  heartbeat_at BIGINT NOT NULL,
  ended_at BIGINT,
  duration_ms BIGINT,
  cost_usd DOUBLE PRECISION,
  num_turns BIGINT,
  tokens_in BIGINT,
  tokens_out BIGINT,
  tokens_cache_read BIGINT,
  tokens_cache_write BIGINT,
  model TEXT,
  exit_code BIGINT,
  error_reason TEXT,
  transcript_path TEXT,
  log_path TEXT,
  report_comment_id BIGINT,
  progress_pct BIGINT,
  progress_note TEXT,
  version BIGINT NOT NULL DEFAULT 1,
  usage_pct DOUBLE PRECISION CHECK (usage_pct IS NULL OR usage_pct BETWEEN -100 AND 100)
);

CREATE TABLE runner_settings (
  workspace_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  daily_cap BIGINT NOT NULL DEFAULT 15 CHECK (daily_cap BETWEEN 0 AND 200),
  night_cap BIGINT NOT NULL DEFAULT 10 CHECK (night_cap BETWEEN 0 AND 200),
  paused_until BIGINT,
  paused_open BIGINT NOT NULL DEFAULT 0 CHECK (paused_open IN (0, 1)),
  paused_by BIGINT,
  paused_at BIGINT,
  version BIGINT NOT NULL DEFAULT 1,
  errands_paused_at BIGINT,
  errands_paused_by BIGINT
);

CREATE TABLE recurrences (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  project_id BIGINT NOT NULL,
  created_by BIGINT NOT NULL,
  template_id BIGINT,
  schedule_id BIGINT,
  starts_on BIGINT NOT NULL,
  ends_on BIGINT,
  max_count BIGINT,
  overlap TEXT NOT NULL DEFAULT 'skip' CHECK (overlap IN ('skip', 'create')),
  next_at BIGINT,
  created_count BIGINT NOT NULL DEFAULT 0,
  skipped_count BIGINT NOT NULL DEFAULT 0,
  last_gig_id BIGINT,
  paused_at BIGINT,
  deleted_at BIGINT,
  created_at BIGINT NOT NULL,
  version BIGINT NOT NULL DEFAULT 1,
  assignees TEXT CHECK (assignees IS NULL OR (assignees::jsonb IS NOT NULL)),
  CHECK (deleted_at IS NOT NULL OR (template_id IS NOT NULL AND schedule_id IS NOT NULL))
);

CREATE TABLE projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  slug TEXT NOT NULL CHECK (slug ~ '^[a-z]' AND length(slug) BETWEEN 2 AND 32),
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 64),
  key TEXT NOT NULL CHECK (key ~ '^[A-Z]' AND length(key) BETWEEN 2 AND 5),
  color TEXT,
  description_md TEXT NOT NULL DEFAULT '' CHECK (length(description_md) <= 65536),
  position DOUBLE PRECISION NOT NULL DEFAULT 0,
  next_gig_number BIGINT NOT NULL DEFAULT 1,
  archived_at BIGINT,
  deleted_at BIGINT,
  created_at BIGINT NOT NULL,
  version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE errands (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  template_id BIGINT,
  schedule_id BIGINT,
  worker_id BIGINT NOT NULL,
  created_by BIGINT NOT NULL,
  on_failure_gig BIGINT NOT NULL DEFAULT 0 CHECK (on_failure_gig IN (0, 1)),
  next_at BIGINT,
  run_now_at BIGINT,
  paused_at BIGINT,
  state TEXT NOT NULL DEFAULT 'never' CHECK (state IN ('never', 'ok', 'failing')),
  fail_streak BIGINT NOT NULL DEFAULT 0,
  failing_since BIGINT,
  last_run_id BIGINT,
  deleted_at BIGINT,
  created_at BIGINT NOT NULL,
  version BIGINT NOT NULL DEFAULT 1,
  project_id BIGINT,
  CHECK (deleted_at IS NOT NULL OR (template_id IS NOT NULL AND schedule_id IS NOT NULL))
);

CREATE TABLE errand_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  errand_id BIGINT NOT NULL,
  workspace_id BIGINT NOT NULL,
  worker_id BIGINT NOT NULL,
  scheduled_for BIGINT,
  started_at BIGINT,
  finished_at BIGINT,
  status TEXT NOT NULL CHECK (status IN ('running', 'ok', 'failed', 'timeout', 'missed', 'skipped')),
  exit_code BIGINT,
  duration_ms BIGINT,
  sandboxed BIGINT NOT NULL DEFAULT 1 CHECK (sandboxed IN (0, 1)),
  output_tail TEXT CHECK (output_tail IS NULL OR octet_length(output_tail) <= 65536),
  output_bytes BIGINT,
  error TEXT CHECK (error IS NULL OR length(error) <= 1000),
  created_at BIGINT NOT NULL
);

CREATE TABLE gig_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT,
  project_id BIGINT,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 250),
  description_md TEXT NOT NULL DEFAULT '' CHECK (length(description_md) <= 65536),
  priority BIGINT NOT NULL DEFAULT 0 CHECK (priority BETWEEN 0 AND 4),
  color TEXT,
  labels TEXT NOT NULL DEFAULT '[]' CHECK ((labels::jsonb IS NOT NULL)),
  assignees TEXT NOT NULL DEFAULT '[]' CHECK ((assignees::jsonb IS NOT NULL)),
  checklist TEXT NOT NULL DEFAULT '[]' CHECK ((checklist::jsonb IS NOT NULL)),
  custom TEXT NOT NULL DEFAULT '{}' CHECK ((custom::jsonb IS NOT NULL)),
  created_by BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  deleted_at BIGINT,
  version BIGINT NOT NULL DEFAULT 1,
  model TEXT NOT NULL DEFAULT '' CHECK (length(model) <= 64),
  effort TEXT NOT NULL DEFAULT '' CHECK (effort IN ('', 'low', 'medium', 'high', 'xhigh', 'max')),
  always_run BIGINT NOT NULL DEFAULT 0 CHECK (always_run IN (0, 1)),
