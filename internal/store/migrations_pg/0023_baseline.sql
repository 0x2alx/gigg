  allowed_listeners TEXT CHECK (allowed_listeners IS NULL OR (allowed_listeners::jsonb IS NOT NULL)),
  allowed_cidrs TEXT CHECK (allowed_cidrs IS NULL OR (allowed_cidrs::jsonb IS NOT NULL)),
  expires_at BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  created_by_user BIGINT,
  created_by_key BIGINT,
  last_used_at BIGINT,
  last_used_listener TEXT,
  last_used_ip TEXT,
  revoked_at BIGINT,
  version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE gig_followers (
  gig_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  PRIMARY KEY (gig_id, user_id)
);

CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  workspace_id BIGINT NOT NULL,
  gig_id BIGINT,
  comment_id BIGINT,
  kind TEXT NOT NULL CHECK (kind IN ('mention', 'assigned', 'question', 'failed', 'missed', 'comment')),
  actor_user_id BIGINT,
  created_at BIGINT NOT NULL,
  read_at BIGINT
);

CREATE TABLE attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  gig_id BIGINT NOT NULL,
  run_id BIGINT,
  kind TEXT NOT NULL CHECK (kind IN ('file', 'link', 'commit')),
  label TEXT NOT NULL DEFAULT '' CHECK (length(label) <= 200),
  value TEXT NOT NULL DEFAULT '' CHECK (length(value) <= 2048),
  blob_sha256 TEXT,
  thumb_sha256 TEXT,
  filename TEXT CHECK (filename IS NULL OR length(filename) BETWEEN 1 AND 255),
  mime TEXT,
  size BIGINT NOT NULL DEFAULT 0,
  width BIGINT,
  height BIGINT,
  created_by BIGINT NOT NULL,
  key_id BIGINT,
  created_at BIGINT NOT NULL,
