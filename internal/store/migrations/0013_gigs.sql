-- Tasks are gigs: tables, columns, index names and the names stored in data
-- (permissions, key scopes, activity actions and keys, MCP tool names in allowed_tools). RENAME keeps
-- foreign keys, indexes and CHECKs pointing at the right things; only index names need recreating.
-- activity is append-only: its guard triggers are lifted for this one rename and put back.
ALTER TABLE tasks RENAME TO gigs;
ALTER TABLE task_aliases RENAME TO gig_aliases;
ALTER TABLE task_assignees RENAME TO gig_assignees;
ALTER TABLE task_labels RENAME TO gig_labels;
ALTER TABLE task_relations RENAME TO gig_relations;
ALTER TABLE task_custom_values RENAME TO gig_custom_values;
ALTER TABLE task_templates RENAME TO gig_templates;
ALTER TABLE gig_aliases RENAME COLUMN task_id TO gig_id;
ALTER TABLE gig_assignees RENAME COLUMN task_id TO gig_id;
ALTER TABLE gig_labels RENAME COLUMN task_id TO gig_id;
ALTER TABLE comments RENAME COLUMN task_id TO gig_id;
ALTER TABLE artifacts RENAME COLUMN task_id TO gig_id;
ALTER TABLE checklist_items RENAME COLUMN task_id TO gig_id;
ALTER TABLE gig_custom_values RENAME COLUMN task_id TO gig_id;
ALTER TABLE notifications RENAME COLUMN task_id TO gig_id;
ALTER TABLE runs RENAME COLUMN task_id TO gig_id;
ALTER TABLE gig_relations RENAME COLUMN from_task_id TO from_gig_id;
ALTER TABLE gig_relations RENAME COLUMN to_task_id TO to_gig_id;
ALTER TABLE gig_templates RENAME COLUMN subtasks TO subgigs;
ALTER TABLE recurrences RENAME COLUMN last_task_id TO last_gig_id;
ALTER TABLE projects RENAME COLUMN next_task_number TO next_gig_number;
DROP INDEX artifacts_task;
CREATE INDEX artifacts_gig ON artifacts(gig_id);
DROP INDEX checklist_task;
CREATE INDEX checklist_gig ON checklist_items(gig_id, position);
DROP INDEX comments_task;
CREATE INDEX comments_gig ON comments(gig_id, id);
DROP INDEX runs_task;
CREATE INDEX runs_gig ON runs(gig_id, id);
DROP INDEX task_relations_to;
CREATE INDEX gig_relations_to ON "gig_relations"(to_gig_id, kind);
DROP INDEX task_templates_ws;
CREATE INDEX gig_templates_ws ON "gig_templates"(workspace_id) WHERE deleted_at IS NULL;
DROP INDEX tasks_archived;
CREATE INDEX gigs_archived ON "gigs"(project_id, archived_at);
DROP INDEX tasks_board;
CREATE INDEX gigs_board ON "gigs"(project_id, status_id, position);
DROP INDEX tasks_parent;
CREATE INDEX gigs_parent ON "gigs"(parent_id) WHERE parent_id IS NOT NULL;
DROP INDEX tasks_recurrence;
CREATE INDEX gigs_recurrence ON "gigs"(recurrence_id, occurrence_at);
DROP INDEX tasks_window;
CREATE INDEX gigs_window ON "gigs"(not_after) WHERE missed_at IS NULL AND deleted_at IS NULL;
DROP INDEX tasks_ws;
CREATE INDEX gigs_ws ON "gigs"(workspace_id, deleted_at);
